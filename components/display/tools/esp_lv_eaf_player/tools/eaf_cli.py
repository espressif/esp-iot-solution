"""Host converter, batch flash packager, C-array generator, and inspector for EAF/EAF4.

Public codec names:
  - 0x04 lossless   : bit-exact BGRA8888 or RGB565+A8
  - 0x05 bounded    : error-bounded 4x4 coding with raw escape
  - 0x06 jpeg-delta : changed-region JPEG strips, no alpha

Only the public codec names are accepted at the CLI boundary.
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

import numpy as np
from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from encoder.eaf4 import INDEX, INDEX_SIZE, FRAME_MODE_NAMES, decode, encode, encode_565  # noqa: E402
from encoder.eaf565 import convert_to_eaf  # noqa: E402
from tools.eaf_inspector.parser import parse_file, print_text  # noqa: E402


from encoder.names import PUBLIC_CODEC_NAMES, PIXFMT_NAMES  # noqa: E402


def _validate_codec(name: str) -> str:
    if name not in PUBLIC_CODEC_NAMES:
        raise ValueError(f'unknown codec: {name}')
    return name


def _natural_sort_key(path: Path) -> tuple:
    parts = re.split(r'(\d+)', path.stem)
    return tuple(int(p) if p.isdigit() else p.lower() for p in parts)


def _load_input_frames(
    inputs: list[str],
    align: int = 4,
    resize: tuple[int, int] | None = None,
) -> list[np.ndarray]:
    """Load RGBA frames from PNG list, directory, GIF, APNG, or video file and return aligned BGRA8888 arrays."""
    pil_frames: list[Image.Image] = []
    if len(inputs) == 1:
        p = Path(inputs[0])
        if p.is_dir():
            pngs = sorted(p.glob('*.png'), key=_natural_sort_key)
            if not pngs:
                raise ValueError(f'No .png files found in directory: {p}')
            for png in pngs:
                with Image.open(png) as im:
                    pil_frames.append(im.convert('RGBA').copy())
        elif p.suffix.lower() in ('.gif', '.apng', '.webp'):
            with Image.open(p) as im:
                for frame in ImageSequence.Iterator(im):
                    pil_frames.append(frame.convert('RGBA').copy())
        elif p.suffix.lower() in ('.mp4', '.avi', '.mov', '.mkv'):
            with tempfile.TemporaryDirectory() as tmp:
                pattern = str(Path(tmp) / 'frame_%04d.png')
                subprocess.run(
                    ['ffmpeg', '-y', '-v', 'error', '-i', str(p), pattern],
                    check=True,
                )
                for png in sorted(Path(tmp).glob('frame_*.png'), key=_natural_sort_key):
                    with Image.open(png) as im:
                        pil_frames.append(im.convert('RGBA').copy())
        else:
            with Image.open(p) as im:
                pil_frames.append(im.convert('RGBA').copy())
    else:
        for item in inputs:
            with Image.open(item) as im:
                pil_frames.append(im.convert('RGBA').copy())

    if not pil_frames:
        raise ValueError('No frames loaded from input')

    bgra_frames: list[np.ndarray] = []
    for im in pil_frames:
        if resize is not None and im.size != resize:
            im = im.resize(resize, Image.Resampling.LANCZOS)
        rgba = np.array(im, dtype=np.uint8)
        h, w, _ = rgba.shape
        pad_h = (align - (h % align)) % align
        pad_w = (align - (w % align)) % align
        if pad_h or pad_w:
            rgba = np.pad(rgba, ((0, pad_h), (0, pad_w), (0, 0)), mode='constant')
        bgra = np.ascontiguousarray(rgba[..., [2, 1, 0, 3]])
        bgra_frames.append(bgra)
    return bgra_frames


def _write_c_header(blob: bytes, header_path: Path, symbol_name: str) -> None:
    symbol = re.sub(r'[^0-9a-zA-Z_]', '_', symbol_name)
    if symbol[0].isdigit():
        symbol = 'eaf_' + symbol
    lines = [
        '/* Auto-generated by esp-eaf-tool. Do not edit. */',
        '#pragma once',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        f'static const size_t {symbol}_size = {len(blob)}U;',
        f'static const uint8_t {symbol}_data[{len(blob)}] __attribute__((aligned(64))) = {{',
    ]
    for i in range(0, len(blob), 16):
        chunk = blob[i : i + 16]
        hex_str = ', '.join(f'0x{b:02x}' for b in chunk)
        lines.append(f'    {hex_str},')
    lines.append('};')
    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text('\n'.join(lines) + '\n')


def _encode_single_to_bytes(
    inputs: list[str],
    fmt: str,
    codec: str,
    period: int,
    key_interval: int,
    max_error: int,
    resize: tuple[int, int] | None = None,
    legacy_container: bool = False,
    clean_alpha: bool | None = None,
    temporal_deadzone: int = 0,
) -> tuple[bytes, dict]:
    _validate_codec(codec)
    if fmt not in ('bgra8888', 'rgb565', 'rgb565a8'):
        raise ValueError(f'unknown pixel format: {fmt}')
    if codec == 'jpeg-delta' and fmt != 'rgb565':
        raise ValueError('jpeg-delta requires --format rgb565')
    if codec == 'bounded' and fmt == 'rgb565a8':
        raise ValueError('bounded supports rgb565 or bgra8888; use bgra8888 for alpha')
    if legacy_container and codec == 'lossless' and fmt != 'rgb565a8':
        raise ValueError('classic EAF lossless requires --format rgb565a8')
    if not 0 <= temporal_deadzone <= 255:
        raise ValueError('--temporal-deadzone must be in 0..255')
    supports_cleanup = fmt == 'bgra8888' and codec in ('lossless', 'bounded') and not legacy_container
    if clean_alpha is None:
        clean_alpha = supports_cleanup
    elif clean_alpha and not supports_cleanup:
        raise ValueError('--clean-alpha requires EAF4 bgra8888 lossless or bounded')
    if temporal_deadzone and (fmt != 'bgra8888' or codec != 'lossless' or legacy_container):
        raise ValueError('--temporal-deadzone requires EAF4 bgra8888 lossless')
    align = 16 if codec == 'jpeg-delta' else 4
    bgra_frames = _load_input_frames(inputs, align=align, resize=resize)
    h, w, _ = bgra_frames[0].shape

    if codec == 'jpeg-delta' or (fmt in ('rgb565', 'rgb565a8') and legacy_container):
        with tempfile.TemporaryDirectory() as tmp:
            tmp_dir = Path(tmp)
            png_paths = []
            for idx, bgra in enumerate(bgra_frames):
                rgba = bgra[..., [2, 1, 0, 3]]
                p = tmp_dir / f'f_{idx:04d}.png'
                Image.fromarray(rgba, 'RGBA').save(p)
                png_paths.append(str(p))
            out_tmp = tmp_dir / 'out.eaf'
            convert_to_eaf(
                files=png_paths,
                out_path=str(out_tmp),
                mode=codec,
                max_error=max_error,
                keyframe_interval=key_interval,
            )
            blob = out_tmp.read_bytes()
            summary = {
                'container': 'EAF',
                'format': fmt.upper(),
                'codec': codec.upper().replace('-', '_'),
                'width': w,
                'height': h,
                'frames': len(bgra_frames),
                'bytes': len(blob),
                'crc32': zlib.crc32(blob) & 0xFFFFFFFF,
            }
            return blob, summary

    if fmt in ('rgb565', 'rgb565a8'):
        blob, summary = encode_565(
            bgra_frames,
            period_ms=period,
            key_interval=key_interval,
            codec=codec,
            max_error=max_error,
            with_alpha=fmt == 'rgb565a8',
        )
        summary['container'] = 'EAF4'
        summary['format'] = fmt.upper()
        summary['codec'] = codec.upper().replace('-', '_')
        summary['crc32'] = zlib.crc32(blob) & 0xFFFFFFFF
        return blob, summary

    blob, summary = encode(
        bgra_frames,
        period_ms=period,
        key_interval=key_interval,
        codec=codec,
        max_error=max_error,
        clean_alpha=clean_alpha,
        temporal_deadzone=temporal_deadzone,
    )
    summary['container'] = 'EAF4'
    summary['format'] = 'BGRA8888'
    summary['codec'] = codec.upper().replace('-', '_')
    summary['crc32'] = zlib.crc32(blob) & 0xFFFFFFFF
    return blob, summary


def _parse_resize(val: str | None) -> tuple[int, int] | None:
    if not val:
        return None
    m = re.match(r'^(\d+)x(\d+)$', val.strip())
    if not m:
        raise ValueError(f"Invalid --resize format '{val}', expected WIDTHxHEIGHT (e.g. 240x240)")
    return int(m.group(1)), int(m.group(2))


def _encode(args: argparse.Namespace) -> int:
    resize = _parse_resize(args.resize)
    codec = _validate_codec(args.codec)
    blob, summary = _encode_single_to_bytes(
        inputs=args.frames,
        fmt=args.format,
        codec=codec,
        period=args.period,
        key_interval=args.key_interval,
        max_error=args.max_error,
        resize=resize,
        legacy_container=getattr(args, 'legacy_container', False),
        clean_alpha=getattr(args, 'clean_alpha', None),
        temporal_deadzone=getattr(args, 'temporal_deadzone', 0),
    )
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(blob)

    if args.c_header:
        sym = args.c_symbol or out_path.stem
        _write_c_header(blob, Path(args.c_header), sym)

    sub_info = f" frame_modes={summary['mode_counts_all']}" if 'mode_counts_all' in summary else ''
    print(
        f"wrote {args.output} container={summary['container']} format={summary['format']} "
        f"codec={summary['codec']} {summary['width']}x{summary['height']} "
        f"frames={summary['frames']} bytes={summary['bytes']}{sub_info}"
    )
    return 0


def _batch(args: argparse.Namespace) -> int:
    in_dir = Path(args.input_dir)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    resize = _parse_resize(args.resize)
    codec = _validate_codec(args.codec)
    legacy_cont = getattr(args, 'legacy_container', False)
    ext = '.eaf4' if (codec in ('lossless', 'bounded') and not legacy_cont) else '.eaf'

    targets: list[tuple[str, list[str]]] = []
    for child in sorted(in_dir.iterdir(), key=_natural_sort_key):
        if child.is_dir() and list(child.glob('*.png')):
            targets.append((child.name, [str(child)]))
        elif child.is_file() and child.suffix.lower() in ('.gif', '.apng', '.mp4', '.avi'):
            targets.append((child.stem, [str(child)]))

    if not targets:
        print(f'No animation folders or (.gif/.apng/.mp4) files found in {in_dir}', file=sys.stderr)
        return 1

    manifest_items = []
    packed_bin = bytearray()

    for name, inp in targets:
        blob, summary = _encode_single_to_bytes(
            inputs=inp,
            fmt=args.format,
            codec=codec,
            period=args.period,
            key_interval=args.key_interval,
            max_error=args.max_error,
            resize=resize,
            legacy_container=legacy_cont,
            clean_alpha=getattr(args, 'clean_alpha', None),
            temporal_deadzone=getattr(args, 'temporal_deadzone', 0),
        )
        file_out = out_dir / f'{name}{ext}'
        file_out.write_bytes(blob)

        offset = len(packed_bin)
        packed_bin.extend(blob)
        pad = (64 - (len(packed_bin) % 64)) % 64
        if pad:
            packed_bin.extend(bytes(pad))

        item = {
            'name': name,
            'file': file_out.name,
            'offset': offset,
            'size': len(blob),
            'width': summary['width'],
            'height': summary['height'],
            'frames': summary['frames'],
            'container': summary['container'],
            'codec': codec.upper().replace('-', '_'),
            'crc32': f"0x{summary['crc32']:08X}",
        }
        manifest_items.append(item)
        print(
            f'[batch] {name:<22} -> {file_out.name:<26} '
            f"{summary['width']}x{summary['height']} {summary['frames']:3d}f {len(blob)/1024:7.1f} KB"
        )

    bin_path = out_dir / 'eaf_assets.bin'
    bin_path.write_bytes(packed_bin)
    manifest_path = out_dir / 'manifest.json'
    manifest_path.write_text(
        json.dumps({'total_bytes': len(packed_bin), 'assets': manifest_items}, indent=2, ensure_ascii=False) + '\n'
    )

    c_hdr_path = out_dir / 'eaf_assets_table.h'
    h_lines = [
        '/* Auto-generated by esp-eaf-tool batch packager. */',
        '#pragma once',
        '#include <stdint.h>',
        '',
        'typedef struct {',
        '    const char *name;',
        '    uint32_t offset;',
        '    uint32_t size;',
        '    uint16_t width;',
        '    uint16_t height;',
        '    uint32_t frames;',
        '    uint32_t crc32;',
        '} eaf_asset_entry_t;',
        '',
        f'#define EAF_ASSET_COUNT {len(manifest_items)}U',
        'static const eaf_asset_entry_t g_eaf_assets[EAF_ASSET_COUNT] = {',
    ]
    for it in manifest_items:
        h_lines.append(
            f'    {{"{it["name"]}", {it["offset"]}U, {it["size"]}U, '
            f'{it["width"]}U, {it["height"]}U, {it["frames"]}U, {it["crc32"]}U}},'
        )
    h_lines.append('};')
    c_hdr_path.write_text('\n'.join(h_lines) + '\n')

    print(
        f'Batch complete: {len(manifest_items)} assets packed into {bin_path} '
        f'({len(packed_bin)/1024:.1f} KB), manifest: {manifest_path}, C header: {c_hdr_path}'
    )
    return 0


def _inspect(args: argparse.Namespace) -> int:
    path = Path(args.file)
    data = path.read_bytes()
    if len(data) >= 4 and data[:4] == b'EAF4':
        frames = decode(data)
        version, _header_size, width, height = struct.unpack_from('<HHHH', data, 4)
        n_frames, period_ms, frame_bytes, index_offset, _data_offset, file_size = struct.unpack_from('<IIIIII', data, 12)
        pixfmt = data[52]
        pixfmt_name = PIXFMT_NAMES.get(pixfmt, f'unknown({pixfmt})')
        counts = [0] * 12
        for i in range(n_frames):
            rec = INDEX.unpack_from(data, index_offset + i * INDEX_SIZE)
            m = rec[4]
            if 0 <= m < len(counts):
                counts[m] += 1
        declared_codec = data[53]
        if declared_codec not in (0, 4, 5):
            raise ValueError(f'Unsupported EAF4 codec ID: {declared_codec}')
        bounded = declared_codec == 5 or (declared_codec == 0 and (counts[6] > 0 or counts[9] > 0))
        codec_id = '0x05 EAF Bounded (BOUNDED)' if bounded else '0x04 EAF Lossless (LOSSLESS)'
        sub_str = ', '.join(f'{FRAME_MODE_NAMES[m]}:{c}' for m, c in enumerate(counts) if c > 0)
        print(
            f'OK {args.file}\n'
            f'  container         : EAF4 ({pixfmt_name} v{version})\n'
            f'  codec             : {codec_id}\n'
            f'  bytes             : {file_size}\n'
            f'  size              : {width}x{height}\n'
            f'  frames            : {len(frames)} (period={period_ms} ms, raw_frame={frame_bytes} B)\n'
            f'  frame_modes    : {sub_str}'
        )
        return 0
    if len(data) >= 4 and data[0] == 0x89 and data[1:4] in (b'EAF', b'AAF'):
        info = parse_file(path, verify_blocks=False)
        print_text(info, verbose=False, print_frames=False)
        return 0 if info.ok else 1
    print(f'Unsupported file header in {args.file}', file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(
        description='ESP EAF/EAF4 tool (lossless, bounded, jpeg-delta)'
    )
    sub = parser.add_subparsers(dest='command', required=True)

    enc = sub.add_parser('encode', help='encode PNG sequence / folder / GIF / APNG / MP4 into EAF4 or EAF')
    enc.add_argument('frames', nargs='+', help='PNG files, a directory of PNGs, or a .gif/.apng/.mp4 file')
    enc.add_argument('-o', '--output', required=True, help='Output .eaf4 or .eaf file')
    enc.add_argument('--format', choices=['bgra8888', 'rgb565', 'rgb565a8'], default='bgra8888', help='Exact output pixel format')
    enc.add_argument(
        '--codec',
        choices=PUBLIC_CODEC_NAMES,
        default='lossless',
        metavar='{lossless,bounded,jpeg-delta}',
        help='public names: lossless, bounded, jpeg-delta',
    )
    enc.add_argument('--period', type=int, default=67, help='EAF4 frame period in ms, 10..10000 (default: 67); not stored in classic EAF')
    enc.add_argument('--key-interval', type=int, default=30, help='Keyframe interval for random seek (default: 30)')
    enc.add_argument(
        '--max-error', dest='max_error', type=int, default=8,
        help='maximum channel error for 0x05 bounded (default: 8)',
    )
    enc.add_argument('--resize', default=None, help='Optional resize WIDTHxHEIGHT (e.g. 240x240)')
    enc.add_argument('--clean-alpha', action=argparse.BooleanOptionalAction, default=None, help='EAF4 BGRA8888: zero hidden RGB at Alpha == 0 (default: on; --no-clean-alpha preserves hidden RGB)')
    enc.add_argument('--temporal-deadzone', type=int, default=0, help='EAF4 BGRA8888 lossless: temporal approximation threshold 0..255 (default: 0, disabled)')
    enc.add_argument('--legacy-container', action='store_true', help='Emit legacy 0x89 EAF container for 565 modes')
    enc.add_argument('--c-header', default=None, help='Optional path to emit C array header (.h)')
    enc.add_argument('--c-symbol', default=None, help='Optional C array identifier name')
    enc.set_defaults(func=_encode)

    bat = sub.add_parser('batch', help='batch-convert a directory of animations and pack a 64B-aligned flash partition image')
    bat.add_argument('input_dir', help='Directory containing animation subfolders or .gif/.apng/.mp4 files')
    bat.add_argument('-o', '--output-dir', required=True, help='Output directory for .eaf4/.eaf, eaf_assets.bin, manifest.json, and eaf_assets_table.h')
    bat.add_argument('--format', choices=['bgra8888', 'rgb565', 'rgb565a8'], default='bgra8888')
    bat.add_argument(
        '--codec',
        choices=PUBLIC_CODEC_NAMES,
        default='lossless',
        metavar='{lossless,bounded,jpeg-delta}',
        help='public codec name',
    )
    bat.add_argument('--period', type=int, default=67)
    bat.add_argument('--key-interval', type=int, default=30)
    bat.add_argument('--max-error', dest='max_error', type=int, default=8)
    bat.add_argument('--resize', default=None)
    bat.add_argument('--clean-alpha', action=argparse.BooleanOptionalAction, default=None, help='EAF4 BGRA8888: zero hidden RGB at Alpha == 0 (default: on; --no-clean-alpha preserves hidden RGB)')
    bat.add_argument('--temporal-deadzone', type=int, default=0, help='EAF4 BGRA8888 lossless: temporal approximation threshold 0..255 (default: 0, disabled)')
    bat.add_argument('--legacy-container', action='store_true', help='Emit legacy 0x89 EAF container for 565 modes')
    bat.set_defaults(func=_batch)

    for cmd in ('info', 'inspect'):
        p = sub.add_parser(cmd, help='auto-detect EAF(0x89) or EAF4 header and inspect contents')
        p.add_argument('file')
        p.set_defaults(func=_inspect)

    args = parser.parse_args()
    try:
        return args.func(args)
    except (OSError, ValueError, struct.error, zlib.error, subprocess.CalledProcessError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
